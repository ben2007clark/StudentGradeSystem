Name = input("Please enter your name: ")
ModuleMark1 = int(input("Please enter your first module mark: "))
ModuleMark2 = int(input("Please enter your second module mark: "))
ModuleMark3 = int(input("Please enter your third module mark: "))
AverageModuleMark = (ModuleMark1 + ModuleMark2 + ModuleMark3) / 3
print(f"average mark: {AverageModuleMark}")
OverallMark = (ModuleMark1 + ModuleMark2 + ModuleMark3)
if OverallMark >= 70:
  ModuleGrade = "First"
elif OverallMark >= 60:
  ModuleGrade = "2:1"
elif OverallMark >= 50:
  ModuleGrade = "2:2"
elif OverallMark >= 40:
  ModuleGrade = "Third"
else:
  ModuleGrade = "Fail"
print (f"Total Marks: {OverallMark}")
print(f"module grade: {ModuleGrade}")
ModuleMarks = [ModuleMark1, ModuleMark2, ModuleMark3]
HighestMark = max(ModuleMarks)
print(f"Highest mark: {HighestMark}")
LowestMark = min(ModuleMarks)
print(f"lowest mark: {LowestMark}")